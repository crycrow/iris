def employee_name(index: int) -> str:
    if index <= len(INITIAL_NAMES):
        first, last = INITIAL_NAMES[index - 1].split()
        female = index % 2 == 0
    else:
        number = index - len(INITIAL_NAMES) - 1
        female = number % 2 == 1
        first = (FEMALE_NAMES if female else MALE_NAMES)[(number // 2) % 12]
    last = SURNAMES[index - 1] + ("а" if female else "")
    patronymic = (FEMALE_PATRONYMICS if female else MALE_PATRONYMICS)[(index - 1) % 12]
    return f"{last} {first} {patronymic}"


